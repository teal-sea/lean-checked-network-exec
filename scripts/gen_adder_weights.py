#!/usr/bin/env python3
"""Generate rust/adder/src/weights.rs from the vendored lean/RnnAdder/Trained.lean.

The Lean file is the source: it is the byte-for-byte copy of lean-checked-network's
rnn/lean/RnnAdder/Trained.lean (scripts/vendor.sh checks that), and it is the object the
theorem RnnAdder.Trained.adds is about. This script reads the integer literals out of it
(`.ofNat n` is n, `.negSucc n` is -(n + 1)) and writes the same numbers as Rust constants.

Usage: scripts/gen_adder_weights.py [--check]
  --check   do not write; exit 1 if rust/adder/src/weights.rs differs from what would be written
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean" / "RnnAdder" / "Trained.lean"
OUT = ROOT / "rust" / "adder" / "src" / "weights.rs"

LIT = re.compile(r"\(\.(ofNat|negSucc) (\d+)\)")


def ints(text):
    return [int(n) if kind == "ofNat" else -(int(n) + 1) for kind, n in LIT.findall(text)]


def field(body, name, last=False):
    """The text of one structure field: from `name :=` to the next `ident :=` or the closing brace."""
    m = re.search(rf"\b{name} := (.*?)(?=,\s*\n\s*\w+ := |\n\}})", body, re.S)
    if not m:
        sys.exit(f"field {name} not found in {LEAN}")
    return m.group(1)


def bools(text):
    return [w == "true" for w in re.findall(r"\b(true|false)\b", text)]


def main():
    src = LEAN.read_bytes()
    text = src.decode("utf-8")
    m = re.search(r"def net : Net := \{(.*?)\n\}", text, re.S)
    if not m:
        sys.exit(f"`def net : Net` not found in {LEAN}")
    body = m.group(1) + "\n}"

    rows = re.findall(r"\[([^\[\]]*)\]", field(body, "Wh"))
    wh = [ints(r) for r in rows]
    h = len(wh)
    vec = {k: ints(field(body, k)) for k in ("Wxa", "Wxb", "bh", "Wo", "Wc")}
    sca = {k: ints(field(body, k)) for k in ("Woa", "Wob", "bo", "bc")}
    h0 = bools(field(body, "h0"))
    reach = [bools(r) for r in re.findall(r"\[([^\[\]]*)\]", field(body, "reach"))]

    assert all(len(r) == h for r in wh), "Wh is not square"
    assert all(len(v) == h for v in vec.values()), "a vector has the wrong length"
    assert all(len(v) == 1 for v in sca.values()), "a scalar field has more than one literal"
    assert len(h0) == h and all(len(r) == h for r in reach), "a state has the wrong length"
    flat = [x for r in wh for x in r] + [x for v in vec.values() for x in v] + [v[0] for v in sca.values()]
    assert all(-127 <= x <= 127 for x in flat), "a weight is outside [-127, 127]"

    def arr(v):
        return "[" + ", ".join(str(x) for x in v) + "]"

    def barr(v):
        return "[" + ", ".join("true" if x else "false" for x in v) + "]"

    lines = [
        "// Generated by scripts/gen_adder_weights.py from lean/RnnAdder/Trained.lean. Do not edit.",
        f"// Source sha256: {hashlib.sha256(src).hexdigest()}",
        "",
        "/// Number of hidden units.",
        f"pub const H: usize = {h};",
        "/// Recurrent weights, one row per unit.",
        "pub const WH: [[i32; H]; H] = [" + ", ".join(arr(r) for r in wh) + "];",
        "/// Input weights for the bit `a`, one per unit.",
        f"pub const WXA: [i32; H] = {arr(vec['Wxa'])};",
        "/// Input weights for the bit `b`, one per unit.",
        f"pub const WXB: [i32; H] = {arr(vec['Wxb'])};",
        "/// Recurrent biases.",
        f"pub const BH: [i32; H] = {arr(vec['bh'])};",
        "/// Sum-bit read-out weights, applied to the new state.",
        f"pub const WO: [i32; H] = {arr(vec['Wo'])};",
        "/// Sum-bit weight for the bit `a`.",
        f"pub const WOA: i32 = {sca['Woa'][0]};",
        "/// Sum-bit weight for the bit `b`.",
        f"pub const WOB: i32 = {sca['Wob'][0]};",
        "/// Sum-bit bias.",
        f"pub const BO: i32 = {sca['bo'][0]};",
        "/// Carry read-out weights.",
        f"pub const WC: [i32; H] = {arr(vec['Wc'])};",
        "/// Carry read-out bias.",
        f"pub const BC: i32 = {sca['bc'][0]};",
        "/// Initial state.",
        f"pub const H0: [bool; H] = {barr(h0)};",
        "/// The states the Lean certificate lists as reachable from `H0`. Not used by the evaluator.",
        f"pub const REACH: [[bool; H]; {len(reach)}] = [" + ", ".join(barr(r) for r in reach) + "];",
        "",
    ]
    out = "\n".join(lines)
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != out:
            sys.exit(f"{OUT} is not what {LEAN} generates")
        print(f"ok: {OUT.relative_to(ROOT)} matches {LEAN.relative_to(ROOT)}")
        return
    OUT.write_text(out)
    print(f"source {LEAN.relative_to(ROOT)} sha256 {hashlib.sha256(src).hexdigest()}")
    print(f"wrote  {OUT.relative_to(ROOT)} sha256 {hashlib.sha256(out.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
