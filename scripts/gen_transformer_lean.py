ROW_IMPORTS = ["TransformerInt.Fast", "TransformerInt.Gen.Weights", "TransformerInt.Gen.Tables",
               "TransformerInt.Gen.Packed", "TransformerInt.Gen.Static", "TransformerInt.Gen.TablesOk"]


# What a statement about `fastPredict` alone needs: no table proofs.
FAST_IMPORTS = ["TransformerInt.Fast", "TransformerInt.Gen.Weights", "TransformerInt.Gen.Tables",
                "TransformerInt.Gen.Packed"]


def write_row(gen_dir, a, chunks):
    """Row `a`: the kernel runs the packed evaluator on every b, in `chunks` declarations."""
    edges = [round(i * P / chunks) for i in range(chunks + 1)]
    parts = []
    for i in range(chunks):
        lo, hi = edges[i], edges[i + 1]
        parts.append(f"""theorem fast_{a}_{i} : ∀ b, b < {hi - lo} →
    fastPredict weights tables bounds packed {a} ({lo} + b) = some (({a} + ({lo} + b)) % 113) := by
  decide +kernel""")
    arms = []
    for i in range(chunks):
        lo, hi = edges[i], edges[i + 1]
        arms.append(f"""  · have h := fast_{a}_{i} (b - {lo}) (by omega)
    rw [show {lo} + (b - {lo}) = b by omega] at h
    exact h""")
    if chunks == 1:
        split = "  have hc : b < 113 := hb\n" + arms[0]
    else:
        conds = " ∨ ".join(f"({edges[i]} ≤ b ∧ b < {edges[i + 1]})" for i in range(chunks))
        split = f"  have hc : {conds} := by omega\n  rcases hc with " + " | ".join(["hc"] * chunks) + "\n" + "\n".join(arms)
    parts.append(f"""/-- The packed evaluator answers ({a} + b) % 113 for every b. -/
theorem fast_{a} : ∀ b, b < 113 → fastPredict weights tables bounds packed {a} b = some (({a} + b) % 113) := by
  intro b hb
{split}

/-- Row {a} of the addition table: the model answers ({a} + b) % 113 for every b. -/
theorem row_{a} : ∀ b, b < 113 → predict weights {a} b = some (({a} + b) % 113) := by
  intro b hb
  exact fastPredict_sound static_ok tables_ok {a} b (by decide) hb _ (fast_{a} b hb)""")
    emit(gen_dir / f"Row{a}.lean", module(ROW_IMPORTS, "\n\n".join(parts), opts="set_option Elab.async false\n"))


def write_all_rows(gen_dir):
    arms = "\n".join(f"  | {a}, _ => exact row_{a}" for a in range(P))
    body = f"""/-- The integer transformer adds mod 113 on every input pair. -/
theorem adds_mod_113 : ∀ a, a < 113 → ∀ b, b < 113 → predict weights a b = some ((a + b) % 113) := by
  intro a ha
  match a, ha with
{arms}
  | n + 113, h => exact absurd h (by omega)"""
    emit(gen_dir / "AllRows.lean", module([f"TransformerInt.Gen.Row{a}" for a in range(P)], body, opts=""))


def write_pair(gen_dir, a, b):
    body = f"""theorem fast_pair_{a}_{b} :
    fastPredict weights tables bounds packed {a} {b} = some {(a + b) % P} := by
  decide +kernel

theorem pair_{a}_{b} : predict weights {a} {b} = some {(a + b) % P} :=
  fastPredict_sound static_ok tables_ok {a} {b} (by decide) (by decide) _ fast_pair_{a}_{b}"""
    emit(gen_dir / f"Pair_{a}_{b}.lean", module(ROW_IMPORTS, body, opts="set_option Elab.async false\n"))


def write_prefix(gen_dir, a, n):
    """The first `n` pairs of row `a` in one declaration, for timing."""
    body = f"""theorem fast_prefix_{a}_{n} : ∀ b, b < {n} →
    fastPredict weights tables bounds packed {a} b = some (({a} + b) % 113) := by
  decide +kernel"""
    emit(gen_dir / f"Prefix_{a}_{n}.lean", module(FAST_IMPORTS, body, opts="set_option Elab.async false\n"))


def write_base(gen_dir):
    """The imports of a row module and nothing to check: what a row module costs before its check."""
    body = "theorem base : (1 : Nat) = 1 := rfl"
    emit(gen_dir / "Base.lean", module(FAST_IMPORTS, body, opts="set_option Elab.async false\n"))


def write_direct(gen_dir, a, b):
    """The model itself in the kernel, no tables and no packing: the baseline."""
    body = f"""theorem direct_{a}_{b} : predict weights {a} {b} = some {(a + b) % P} := by
  decide +kernel"""
    emit(gen_dir / f"Direct_{a}_{b}.lean", module(
        ["TransformerInt.Model", "TransformerInt.Gen.Weights"], body, opts="set_option Elab.async false\n"))


def write_eval(gen_dir, model, pairs):
    """`#eval` of the Lean model against the Python reference: a test, not a proof."""
    defs, rows = [], []
    for a, b in pairs:
        out, _ = model.forward(a, b)
        defs.append(f"def ref_{a}_{b} : List Int := {vec(out)}")
        rows.append(f"({a}, {b}, ref_{a}_{b})")
    # One def per pair: a single def of 27,798 literals exceeds the elaborator's recursion depth.
    body = f"""{chr(10).join(defs)}

/-- Logits of the Python reference `scripts/check_transformer_int.py`: `(a, b, logits)`. -/
def expected : List (Nat × Nat × List Int) := [
  {", ".join(rows)}]

/-- Pairs on which the Lean model's logits differ from the reference. -/
def mismatches : List (Nat × Nat) :=
  (expected.filter fun (a, b, l) => logits weights a b != some l).map fun (a, b, _) => (a, b)

/-- Pairs on which the Lean model's answer is not `(a + b) % 113`. -/
def wrong : List (Nat × Nat) :=
  (expected.filter fun (a, b, _) => predict weights a b != some ((a + b) % 113)).map fun (a, b, _) => (a, b)

#eval s!"pairs compared: {{expected.length}}; logits compared: {{(expected.map fun (_, _, l) => l.length).sum}}"
#eval s!"pairs with a different logit: {{mismatches.length}} {{mismatches}}"
#eval s!"pairs with a wrong answer: {{wrong.length}} {{wrong}}"
#guard mismatches.isEmpty && wrong.isEmpty"""
    emit(gen_dir / "Eval.lean", module(["TransformerInt.Model", "TransformerInt.Gen.Weights"], body))


