#!/usr/bin/env python3
"""Generate the Lean project that kernel-checks the integer transformer (gate 4 pilot).

Standard library only. The integers come from gen_transformer_weights.py (same checkpoint, same
quantisation, same exponential tables), so the Lean model reads what rust/transformer/src/weights.rs
holds. The score and value tables come from check_transformer_int.py, the exact Python reference.

The output directory becomes a standalone Lake project (core Lean, no Mathlib):

  hand-written, copied from pilot/transformer-int/ unless OUT is that directory:
    lakefile.toml, lean-toolchain, TransformerInt.lean
    TransformerInt/Model.lean     the model of rust/transformer/src/lib.rs, on Int
    TransformerInt/Fast.lean      the packed evaluator and the proof that it equals the model
  generated, everything under TransformerInt/Gen/:
    W/*.lean                      data only, no imports: the weights and the four exponential
                                  tables; TablesData (attention scores and value vectors per head,
                                  position and token); PackedData (rows of WO, WIN, WOUT, U packed)
    Weights.lean, Tables.lean, Packed.lean   the same data as the structures of Model and Fast
    Static.lean                   shapes, entry bounds and the packed rows (kernel-checked)
    TabOk{0..3}.lean, TablesOk.lean   every table entry equals its definition (kernel-checked)
    Row{a}.lean                   theorem row_{a} : for every b < 113, predict a b = (a + b) % 113
    AllRows.lean                  adds_mod_113, only with all 113 rows
    Eval.lean                     #eval of the model against the Python reference logits (a test)
    Pair_{a}_{b}.lean, Direct_{a}_{b}.lean   single pairs, for timing (--pairs, --direct)
    Prefix_{a}_{n}.lean, Base.lean           the first n pairs of row a (--prefix a:n); imports only

Usage:
  gen_transformer_lean.py CHECKPOINT.npz OUT [--rows 0,21 | --rows all] [--pairs 0:0,21:56]
                          [--direct 0:0] [--prefix 0:8] [--eval-rows 0,21] [--chunks N] [--hand-only]
  --rows       the rows to write a module for (default: 0,21)
  --chunks     split a row's kernel check into N declarations (default 1)
  --hand-only  copy the hand-written files and stop
  --allow-other-checkpoint   skip the sha256 pin (for experiments only)
"""

import argparse
import hashlib
import re
import shutil
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no scripts/__pycache__ in the repository
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_transformer_int as ref  # noqa: E402
import gen_transformer_weights as gen  # noqa: E402

ROOT = gen.ROOT
HAND = ROOT / "pilot" / "transformer-int"
HAND_FILES = [
    "lakefile.toml",
    "lean-toolchain",
    "TransformerInt.lean",
    "TransformerInt/Model.lean",
    "TransformerInt/Fast.lean",
]

P, EQ = ref.P, ref.EQ
N_HEADS, D_MODEL, D_HEAD, D_MLP = ref.N_HEADS, ref.D_MODEL, ref.D_HEAD, ref.D_MLP

HEADER = "-- @generated by scripts/gen_transformer_lean.py. Do not edit.\n"


def packing_base():
    """`B` of TransformerInt/Fast.lean. A wrong value here makes Static.lean fail in the kernel."""
    m = re.search(r"^def B : Nat := (\d+)$", (HAND / "TransformerInt" / "Fast.lean").read_text(), re.M)
    if not m:
        raise ValueError("Fast.lean: no line `def B : Nat := <number>`")
    return int(m.group(1))


def pk(row, base):
    """`pkI` of Fast.lean: signed digits `row[0] + base * (row[1] + base * (...))`."""
    acc = 0
    for d in reversed(row):
        acc = d + base * acc
    return acc
OPTS = "set_option maxRecDepth 100000\nset_option maxHeartbeats 4000000\n"


def lit(x):
    """An Int literal written as a constructor, so the kernel does no typeclass unfolding."""
    return f"(.ofNat {x})" if x >= 0 else f"(.negSucc {-x - 1})"


def vec(v):
    return "[" + ", ".join(lit(x) for x in v) + "]"


def hexvec(v):
    """Packed rows have thousands of digits; hexadecimal is linear to write and to read."""
    return "[" + ", ".join(f"(.ofNat 0x{x:x})" if x >= 0 else f"(.negSucc 0x{-x - 1:x})" for x in v) + "]"


def names(prefix, n):
    return "[" + ", ".join(f"{prefix}_{i}" for i in range(n)) + "]"


def matrix(prefix, rows, doc):
    """One def per row (a def of 65,536 literals is too deep for the elaborator), then the list."""
    out = [f"def {prefix}_{i} : List Int := {vec(r)}" for i, r in enumerate(rows)]
    out.append("")
    out.append(f"/-- {doc} -/")
    out.append(f"def {prefix} : List (List Int) := {names(prefix, len(rows))}")
    return "\n".join(out)


def module(imports, body, opts=OPTS, ns="TransformerInt.Gen"):
    """A generated module. Without imports it holds data only and opens nothing."""
    imp = "".join(f"import {m}\n" for m in imports) + ("\n" if imports else "")
    opn = "open TransformerInt\n\n" if imports else ""
    return f"{HEADER}{imp}{opts}\nnamespace {ns}\n\n{opn}{body}\n\nend {ns}\n"


def emit(path, text):
    """Write `text` unless the file already holds it, so an unchanged module keeps its mtime."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def absmax(nested):
    while isinstance(nested[0], list):
        nested = [v for row in nested for v in row]
    return max(max(nested), -min(nested))


