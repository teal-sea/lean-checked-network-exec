#!/usr/bin/env python3
"""Generate rust/adder/src/weights.rs, c/adder/weights.h and verilog/adder/rnn_adder.sv from the vendored
lean/RnnAdder/Trained.lean.

The Lean file is the source: it is the byte-for-byte copy of lean-checked-network's
rnn/lean/RnnAdder/Trained.lean (scripts/vendor.sh checks that), and it is the object the
theorem RnnAdder.Trained.adds is about. This script reads the integer literals out of it
(`.ofNat n` is n, `.negSucc n` is -(n + 1)) and writes the same numbers as Rust constants, as C
constants, and as the constants of a SystemVerilog module.

Usage: scripts/gen_adder_weights.py [--check]
  --check   do not write; exit 1 if either generated file differs from what would be written
"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN = ROOT / "lean" / "RnnAdder" / "Trained.lean"
OUT = ROOT / "rust" / "adder" / "src" / "weights.rs"
OUT_C = ROOT / "c" / "adder" / "weights.h"
OUT_SV = ROOT / "verilog" / "adder" / "rnn_adder.sv"

LIT = re.compile(r"\(\.(ofNat|negSucc) (\d+)\)")


def ints(text):
    return [int(n) if kind == "ofNat" else -(int(n) + 1) for kind, n in LIT.findall(text)]


def field(body, name, last=False):
    """The text of one structure field: from `name :=` to the next `ident :=` or the closing brace."""
    m = re.search(rf"\b{name} := (.*?)(?=,\s*\n\s*\w+ := |\n\}})", body, re.S)
    if not m:
        sys.exit(f"field {name} not found in {LEAN}")
    return m.group(1)


def bools(text):
    return [w == "true" for w in re.findall(r"\b(true|false)\b", text)]


def main():
    src = LEAN.read_bytes()
    text = src.decode("utf-8")
    m = re.search(r"def net : Net := \{(.*?)\n\}", text, re.S)
    if not m:
        sys.exit(f"`def net : Net` not found in {LEAN}")
    body = m.group(1) + "\n}"

    rows = re.findall(r"\[([^\[\]]*)\]", field(body, "Wh"))
    wh = [ints(r) for r in rows]
    h = len(wh)
    vec = {k: ints(field(body, k)) for k in ("Wxa", "Wxb", "bh", "Wo", "Wc")}
    sca = {k: ints(field(body, k)) for k in ("Woa", "Wob", "bo", "bc")}
    h0 = bools(field(body, "h0"))
    reach = [bools(r) for r in re.findall(r"\[([^\[\]]*)\]", field(body, "reach"))]

    assert all(len(r) == h for r in wh), "Wh is not square"
    assert all(len(v) == h for v in vec.values()), "a vector has the wrong length"
    assert all(len(v) == 1 for v in sca.values()), "a scalar field has more than one literal"
    assert len(h0) == h and all(len(r) == h for r in reach), "a state has the wrong length"
    flat = [x for r in wh for x in r] + [x for v in vec.values() for x in v] + [v[0] for v in sca.values()]
    assert all(-127 <= x <= 127 for x in flat), "a weight is outside [-127, 127]"

    def arr(v):
        return "[" + ", ".join(str(x) for x in v) + "]"

    def barr(v):
        return "[" + ", ".join("true" if x else "false" for x in v) + "]"

    lines = [
        "// Generated by scripts/gen_adder_weights.py from lean/RnnAdder/Trained.lean. Do not edit.",
        f"// Source sha256: {hashlib.sha256(src).hexdigest()}",
        "",
        "/// Number of hidden units.",
        f"pub const H: usize = {h};",
        "/// Recurrent weights, one row per unit.",
        "pub const WH: [[i32; H]; H] = [" + ", ".join(arr(r) for r in wh) + "];",
        "/// Input weights for the bit `a`, one per unit.",
        f"pub const WXA: [i32; H] = {arr(vec['Wxa'])};",
        "/// Input weights for the bit `b`, one per unit.",
        f"pub const WXB: [i32; H] = {arr(vec['Wxb'])};",
        "/// Recurrent biases.",
        f"pub const BH: [i32; H] = {arr(vec['bh'])};",
        "/// Sum-bit read-out weights, applied to the new state.",
        f"pub const WO: [i32; H] = {arr(vec['Wo'])};",
        "/// Sum-bit weight for the bit `a`.",
        f"pub const WOA: i32 = {sca['Woa'][0]};",
        "/// Sum-bit weight for the bit `b`.",
        f"pub const WOB: i32 = {sca['Wob'][0]};",
        "/// Sum-bit bias.",
        f"pub const BO: i32 = {sca['bo'][0]};",
        "/// Carry read-out weights.",
        f"pub const WC: [i32; H] = {arr(vec['Wc'])};",
        "/// Carry read-out bias.",
        f"pub const BC: i32 = {sca['bc'][0]};",
        "/// Initial state.",
        f"pub const H0: [bool; H] = {barr(h0)};",
        "/// The states the Lean certificate lists as reachable from `H0`. Not used by the evaluator.",
        f"pub const REACH: [[bool; H]; {len(reach)}] = [" + ", ".join(barr(r) for r in reach) + "];",
        "",
    ]
    out = "\n".join(lines)

    def carr(v):
        return "{" + ", ".join(str(x) for x in v) + "}"

    def cbarr(v):
        return "{" + ", ".join("true" if x else "false" for x in v) + "}"

    c_lines = [
        "/* Generated by scripts/gen_adder_weights.py from lean/RnnAdder/Trained.lean. Do not edit. */",
        f"/* Source sha256: {hashlib.sha256(src).hexdigest()} */",
        "#ifndef ADDER_WEIGHTS_H",
        "#define ADDER_WEIGHTS_H",
        "",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        "",
        "/* Number of hidden units. */",
        f"#define ADDER_H {h}",
        "",
        "/* Recurrent weights, one row per unit. */",
        "static const int32_t ADDER_WH[ADDER_H][ADDER_H] = {" + ", ".join(carr(r) for r in wh) + "};",
        "/* Input weights for the bit a, one per unit. */",
        f"static const int32_t ADDER_WXA[ADDER_H] = {carr(vec['Wxa'])};",
        "/* Input weights for the bit b, one per unit. */",
        f"static const int32_t ADDER_WXB[ADDER_H] = {carr(vec['Wxb'])};",
        "/* Recurrent biases. */",
        f"static const int32_t ADDER_BH[ADDER_H] = {carr(vec['bh'])};",
        "/* Sum-bit read-out weights, applied to the new state. */",
        f"static const int32_t ADDER_WO[ADDER_H] = {carr(vec['Wo'])};",
        "/* Sum-bit weights for the bits a and b, and the sum-bit bias. */",
        f"static const int32_t ADDER_WOA = {sca['Woa'][0]};",
        f"static const int32_t ADDER_WOB = {sca['Wob'][0]};",
        f"static const int32_t ADDER_BO = {sca['bo'][0]};",
        "/* Carry read-out weights and bias. */",
        f"static const int32_t ADDER_WC[ADDER_H] = {carr(vec['Wc'])};",
        f"static const int32_t ADDER_BC = {sca['bc'][0]};",
        "/* Initial state. */",
        f"static const bool ADDER_H0[ADDER_H] = {cbarr(h0)};",
        "",
        "#endif",
        "",
    ]
    out_c = "\n".join(c_lines)

    # SystemVerilog: the network as a synchronous circuit, one flip-flop per hidden unit.
    width = 12  # signed bits of a pre-activation
    worst = max(
        max(sum(abs(x) for x in wh[i]) + abs(vec["Wxa"][i]) + abs(vec["Wxb"][i]) + abs(vec["bh"][i]) for i in range(h)),
        sum(abs(x) for x in vec["Wo"]) + abs(sca["Woa"][0]) + abs(sca["Wob"][0]) + abs(sca["bo"][0]),
        sum(abs(x) for x in vec["Wc"]) + abs(sca["bc"][0]),
    )
    assert worst < 2 ** (width - 1), "a pre-activation does not fit the signed width"

    def lit(x):
        return f"-{width}'sd{-x}" if x < 0 else f"{width}'sd{x}"

    def term(cond, w):
        return f"({cond} ? {lit(w)} : {width}'sd0)"

    def pre(name, state, ws, extra, bias):
        parts = [term(f"{state}[{j}]", w) for j, w in enumerate(ws)] + extra + [f"({lit(bias)})"]
        return f"        {name} = " + "\n            + ".join(parts) + ";"

    sv = [
        "// Generated by scripts/gen_adder_weights.py from lean/RnnAdder/Trained.lean. Do not edit.",
        f"// Source sha256: {hashlib.sha256(src).hexdigest()}",
        "//",
        "// The trained recurrent adder of RnnAdder.Network as a synchronous circuit.",
        "//",
        f"// The hidden state is {h} flip-flops, h[i] for unit i. Each cycle the circuit reads one bit of",
        "// each of two numbers, least significant bit first, and drives the sum bit for that position",
        "// on `sum`. `carry` is the carry read off the current state. Every weight is an integer and",
        "// every activation is a threshold at zero:",
        "//",
        "//   n[i]  = [ sum over j of WH[i][j] * h[j] + WXA[i] * a + WXB[i] * b + BH[i] > 0 ]   next state",
        "//   sum   = [ sum over i of WO[i] * n[i] + WOA * a + WOB * b + BO > 0 ]",
        "//   carry = [ sum over i of WC[i] * h[i] + BC > 0 ]",
        "//",
        "// The reset is synchronous and loads the initial state H0. The largest absolute value a",
        f"// pre-activation can take is {worst}, so {width} signed bits hold it.",
        "module rnn_adder (",
        "    input  logic clk,",
        "    input  logic reset,",
        "    input  logic a,",
        "    input  logic b,",
        "    output logic sum,",
        "    output logic carry",
        ");",
        f"    logic [{h - 1}:0] h;  // the hidden state",
        f"    logic [{h - 1}:0] n;  // the next state",
        "",
        "    // Pre-activations: one per hidden unit, one for the sum bit, one for the carry.",
        f"    logic signed [{width - 1}:0] " + ", ".join(f"z{i}" for i in range(h)) + ", zo, zc;",
        "",
        "    always_comb begin",
    ]
    for i in range(h):
        sv.append(pre(f"z{i}", "h", wh[i], [term("a", vec["Wxa"][i]), term("b", vec["Wxb"][i])], vec["bh"][i]))
        sv.append(f"        n[{i}] = z{i} > {width}'sd0;")
    sv.append(pre("zo", "n", vec["Wo"], [term("a", sca["Woa"][0]), term("b", sca["Wob"][0])], sca["bo"][0]))
    sv.append(f"        sum = zo > {width}'sd0;")
    sv.append(pre("zc", "h", vec["Wc"], [], sca["bc"][0]))
    sv.append(f"        carry = zc > {width}'sd0;")
    h0_bits = "".join("1" if h0[i] else "0" for i in reversed(range(h)))
    sv += [
        "    end",
        "",
        "    always_ff @(posedge clk) begin",
        "        if (reset) begin",
        f"            h <= {h}'b{h0_bits};  // H0",
        "        end else begin",
        "            h <= n;",
        "        end",
        "    end",
        "endmodule",
        "",
    ]
    out_sv = "\n".join(sv)

    targets = [(OUT, out), (OUT_C, out_c), (OUT_SV, out_sv)]
    if "--check" in sys.argv[1:]:
        for path, text_out in targets:
            if not path.exists() or path.read_text() != text_out:
                sys.exit(f"{path} is not what {LEAN} generates")
            print(f"ok: {path.relative_to(ROOT)} matches {LEAN.relative_to(ROOT)}")
        return
    print(f"source {LEAN.relative_to(ROOT)} sha256 {hashlib.sha256(src).hexdigest()}")
    for path, text_out in targets:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text_out)
        print(f"wrote  {path.relative_to(ROOT)} sha256 {hashlib.sha256(text_out.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
