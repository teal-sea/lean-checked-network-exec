#!/usr/bin/env python3
"""Generate rust/mlp/src/weights.rs from lean-checked-network's network/trained.npz.

trained.npz holds the frozen integer tables E1q, E2q and W2q (113 x 128 each) that the theorem
LeanCheckedNetwork.Trained.adds_mod_113 is about. This script copies those integers into Rust
`static` tables of `i8`. It reads the .npz with the standard library only (an .npz is a zip of
.npy files), so it needs no numpy.

Usage: scripts/gen_mlp_weights.py PATH/TO/lean-checked-network [--check]
  --check   do not write; exit 1 if rust/mlp/src/weights.rs differs from what would be written
"""
import ast
import hashlib
import struct
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "rust" / "mlp" / "src" / "weights.rs"
P, HID = 113, 128


def read_npy(raw):
    """A little-endian int64 C-order array from .npy bytes, as (shape, flat list)."""
    assert raw[:6] == b"\x93NUMPY", "not an .npy file"
    major = raw[6]
    if major == 1:
        (hlen,) = struct.unpack("<H", raw[8:10]); start = 10
    else:
        (hlen,) = struct.unpack("<I", raw[8:12]); start = 12
    header = ast.literal_eval(raw[start:start + hlen].decode("latin1"))
    assert header["descr"] == "<i8", f"expected int64, got {header['descr']}"
    assert not header["fortran_order"], "expected C order"
    shape = header["shape"]
    n = 1
    for d in shape:
        n *= d
    data = raw[start + hlen:]
    assert len(data) == 8 * n, "data length does not match the shape"
    return shape, list(struct.unpack(f"<{n}q", data))


def table(name, doc, flat):
    rows = []
    for r in range(P):
        row = flat[r * HID:(r + 1) * HID]
        rows.append("    [" + ", ".join(str(x) for x in row) + "],")
    return [f"/// {doc}", f"pub static {name}: [[i8; HID]; P] = ["] + rows + ["];"]


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    npz = Path(args[0]) / "network" / "trained.npz"
    src = npz.read_bytes()
    with zipfile.ZipFile(npz) as z:
        arrays = {k: read_npy(z.read(f"{k}.npy")) for k in ("p", "H", "E1q", "E2q", "W2q")}
    assert arrays["p"][1] == [P] and arrays["H"][1] == [HID], "unexpected modulus or width"
    for k in ("E1q", "E2q", "W2q"):
        shape, flat = arrays[k]
        assert shape == (P, HID), f"{k} has shape {shape}"
        assert all(-128 <= x <= 127 for x in flat), f"{k} does not fit i8"
    lo = min(min(arrays[k][1]) for k in ("E1q", "E2q", "W2q"))
    hi = max(max(arrays[k][1]) for k in ("E1q", "E2q", "W2q"))

    lines = [
        "// Generated by scripts/gen_mlp_weights.py from lean-checked-network network/trained.npz. Do not edit.",
        f"// Source sha256: {hashlib.sha256(src).hexdigest()}",
        f"// Smallest entry {lo}, largest entry {hi}.",
        "",
        "/// The modulus: inputs and answers are in `0..P`.",
        f"pub const P: usize = {P};",
        "/// Number of hidden neurons.",
        f"pub const HID: usize = {HID};",
    ]
    lines += table("E1", "Embedding of the first input: row `a`, one entry per neuron.", arrays["E1q"][1])
    lines += table("E2", "Embedding of the second input: row `b`, one entry per neuron.", arrays["E2q"][1])
    lines += table("W2", "Read-out weights: row `c` scores the candidate answer `c`, one entry per neuron.", arrays["W2q"][1])
    out = "\n".join(lines) + "\n"
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != out:
            sys.exit(f"{OUT} is not what {npz} generates")
        print(f"ok: {OUT.relative_to(ROOT)} matches {npz}")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out)
    print(f"source {npz} sha256 {hashlib.sha256(src).hexdigest()}")
    print(f"wrote  {OUT.relative_to(ROOT)} sha256 {hashlib.sha256(out.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
