def write_weights(gen_dir, t, checkpoint_sha):
    w = gen_dir / "W"
    w.mkdir(parents=True, exist_ok=True)
    base = []  # the data modules import nothing, so a change to the model does not rebuild them
    emb = "\n\n".join([
        matrix("tok", t["tok"], "Token embedding, scale 2^8: 114 rows of 128."),
        matrix("pos", t["pos"], "Position embedding, scale 2^8: 3 rows of 128."),
        f"/-- MLP input bias, scale 2^32. -/\ndef bin : List Int := {vec(t['bin'])}",
        f"/-- MLP output bias, scale 2^40. -/\ndef bout : List Int := {vec(t['bout'])}",
        f"/-- `expN[n]` = round(2^30 * exp(-n)). -/\ndef expN : List Int := {vec(t['EXP_N'])}",
        f"/-- `exp2[b]` = round(2^30 * exp(-b / 2^8)). -/\ndef exp2 : List Int := {vec(t['EXP_2'])}",
        f"/-- `exp1[b]` = round(2^30 * exp(-b / 2^16)). -/\ndef exp1 : List Int := {vec(t['EXP_1'])}",
        f"/-- `exp0[b]` = round(2^30 * exp(-b / 2^24)). -/\ndef exp0 : List Int := {vec(t['EXP_0'])}",
    ])
    emit(w / "Emb.lean", module(base, emb))
    mods = ["Emb"]
    docs = {
        "WQ": "Query matrices, scale 2^8, with 1/sqrt(32) folded in: head, stream index, head index.",
        "WK": "Key matrices, scale 2^8: head, stream index, head index.",
        "WV": "Value matrices, scale 2^8: head, stream index, head index.",
        "WO": "Output matrices, scale 2^8: head, head index, stream index.",
    }
    for name in ("WQ", "WK", "WV", "WO"):
        low = name.lower()
        parts = [matrix(f"{low}_{h}", t[name][h], f"Head {h} of `{low}`.") for h in range(N_HEADS)]
        parts.append(f"/-- {docs[name]} -/\ndef {low} : List (List (List Int)) := {names(low, N_HEADS)}")
        emit(w / f"{name}.lean", module(base, "\n\n".join(parts)))
        mods.append(name)
    emit(w / "Win.lean", module(base, matrix("win", t["Win"], "MLP input matrix, scale 2^8: stream index, hidden index.")))
    emit(w / "Wout.lean", module(base, matrix("wout", t["Wout"], "MLP output matrix, scale 2^8: hidden index, stream index.")))
    emit(w / "U.lean", module(base, matrix("u", t["U"], "Unembedding, scale 2^8: stream index, answer.")))
    mods += ["Win", "Wout", "U"]
    body = f"""/-- The weights of `rust/transformer/src/weights.rs`.
Checkpoint: lean-checked-network transformer/runs/best.npz, sha256 {checkpoint_sha}.
Quantisation: gen_transformer_weights.py quantise, S = {gen.S}. `.ofNat n` is the integer n and
`.negSucc n` is the integer -(n + 1). -/
def weights : Weights := {{
  tok := tok, pos := pos, wq := wq, wk := wk, wv := wv, wo := wo,
  win := win, bin := bin, wout := wout, bout := bout, u := u,
  expN := expN, exp2 := exp2, exp1 := exp1, exp0 := exp0 }}"""
    emit(gen_dir / "Weights.lean", module(["TransformerInt.Model"] + [f"TransformerInt.Gen.W.{m}" for m in mods], body, opts=""))


