#!/usr/bin/env python3
"""Emit runtime arrays and kernel certificates from gate 4's pinned quantisation.
No unchecked arithmetic facts are used by Lean. --check compares every emitted byte.
"""
import argparse
import hashlib
import json
from pathlib import Path
import gen_transformer_weights as gen
import gen_transformer_lean as gate

ROOT = Path(__file__).resolve().parent.parent
FIELDS = [('tok','tok',68,128,'Emb'),('pos','pos',59,128,'Emb'),('wq','WQ',5,32,'WQ'),('wk','WK',22,32,'WK'),('wv','WV',106,32,'WV'),('wo','WO',93,128,'WO'),('win','Win',82,512,'Win'),('wout','Wout',74,128,'Wout'),('u','U',37,113,'U')]
VECTORS = [('bin','bin',1073741824,512),('bout','bout',137438953472,128),('exp_n','EXP_N',None,32),('exp_2','EXP_2',None,256),('exp_1','EXP_1',None,256),('exp_0','EXP_0',None,256)]

def render(t):
    files = {}
    def module(name, imports, body):
        path = f'lean/LcnExec/Engine/Trained/{name}.lean'
        if path in files:
            files[path] = files[path].replace('\nend LcnExec.Engine.TrainedData\n', '\n'+body+'\nend LcnExec.Engine.TrainedData\n')
            return
        files[path] = '-- Generated by scripts/gen_engine_trained.py. Do not edit.\n'+''.join(f'import {x}\n' for x in imports)+'\nopen Aeneas Aeneas.Std Result\nset_option maxRecDepth 100000\nset_option maxHeartbeats 4000000\nset_option Elab.async false\nnamespace LcnExec.Engine.TrainedData\n'+body+'\nend LcnExec.Engine.TrainedData\n'
    allnames=[]
    for field,key,bound,width,mod in FIELDS:
        parts=[]; mats=t[key] if field in ('wq','wk','wv','wo') else [t[key]]
        for h,mat in enumerate(mats):
            prefix=f'{field}_{h}' if len(mats)>1 else field
            for i,row in enumerate(mat):
                name=f'{prefix}_{i}'
                ints=f'TransformerInt.Gen.{name}'
                parts += [f'def {name} : Array I8 {width}#usize := Array.from ({ints}.map encode8) (by decide)',f'theorem {name}_view : {name}.val.map (·.val) = {ints} := by decide +kernel',f'theorem {name}_bound : ∀ v ∈ {name}.val, -({bound} : Int) ≤ v.val ∧ v.val ≤ {bound} := by decide +kernel']
            names=', '.join(f'{prefix}_{i}' for i in range(len(mat)))
            parts += [f'def {prefix} : Array (Array I8 {width}#usize) {len(mat)}#usize := Array.from [{names}] (by decide)',f'theorem {prefix}_view : {prefix}.val.map (fun r => r.val.map (·.val)) = TransformerInt.Gen.{prefix} := by\n  simp only [{prefix}, TransformerInt.Gen.{prefix}, Array.from_val, List.map_cons, List.map_nil, '+', '.join(f'{prefix}_{i}_view' for i in range(len(mat)))+']',f'theorem {prefix}_bound : MatrixBound {bound} {prefix} := by\n  intro r hr\n  simp only [{prefix}, Array.from_val, List.mem_cons, List.not_mem_nil, or_false] at hr\n  rcases hr with '+ ' | '.join(['rfl']*len(mat))+'\n'+ ''.join(f'  · exact {prefix}_{i}_bound\n' for i in range(len(mat)))]
        if len(mats)>1:
            names=', '.join(f'{field}_{h}' for h in range(4))
            parts += [f'def {field} : Array (Array (Array I8 {width}#usize) {len(mats[0])}#usize) 4#usize := Array.from [{names}] (by decide)',f'theorem {field}_view : {field}.val.map (fun m => m.val.map (fun r => r.val.map (·.val))) = TransformerInt.Gen.{field} := by\n  simp only [{field}, TransformerInt.Gen.{field}, Array.from_val, List.map_cons, List.map_nil, '+', '.join(f'{field}_{h}_view' for h in range(4))+']',f'theorem {field}_bound : TensorBound {bound} {field} := by\n  intro m hm\n  simp only [{field}, Array.from_val, List.mem_cons, List.not_mem_nil, or_false] at hm\n  rcases hm with rfl | rfl | rfl | rfl\n'+''.join(f'  · exact {field}_{h}_bound\n' for h in range(4))]
        if field == 'wout':
            # Give the list spine explicitly instead of a 512-way tactic search.
            parts = [p for p in parts if not p.startswith('theorem wout_view') and not p.startswith('theorem wout_bound')]
            view = 'rfl'
            bounds = '(List.forall_mem_nil _)'
            for i in reversed(range(len(t[key]))):
                view = f'(congrArg₂ List.cons wout_{i}_view {view})'
                bounds = f'(List.forall_mem_cons.mpr ⟨wout_{i}_bound, {bounds}⟩)'
            parts += [f'theorem wout_view : wout.val.map (fun r => r.val.map (·.val)) = TransformerInt.Gen.wout := by\n  exact {view}', f'theorem wout_bound : MatrixBound {bound} wout := by\n  exact {bounds}']
        module(mod,['LcnExec.Engine.Stages',f'TransformerInt.Gen.W.{mod}'],'\n\n'.join(parts)); allnames.append(mod)
    parts=[]
    for field,key,bound,n in VECTORS:
        model={'exp_n':'expN','exp_2':'exp2','exp_1':'exp1','exp_0':'exp0'}.get(field,field)
        pred=f'Bounded {bound} {field}' if bound else f'TableBound {field}'
        parts += [f'def {field} : Array I64 {n}#usize := Array.from (TransformerInt.Gen.{model}.map encode64) (by decide)',f'theorem {field}_view : {field}.val.map (·.val) = TransformerInt.Gen.{model} := by decide +kernel',f'theorem {field}_bound : {pred} := by\n  unfold '+('Bounded' if bound else 'TableBound')+'\n  decide +kernel']
    module('Vectors',['LcnExec.Engine.Stages','TransformerInt.Gen.W.Emb'],'\n\n'.join(parts)); allnames.append('Vectors')
    fields=[x[0] for x in FIELDS+VECTORS]
    module('Weights',[f'LcnExec.Engine.Trained.{m}' for m in dict.fromkeys(allnames)]+['TransformerInt.Gen.Weights'], 'def trainedRust : engine.Weights where\n'+''.join(f'  {f} := {f}\n' for f in fields)+'\ntheorem trained_bounds : LoadBounds trainedRust where\n'+''.join(f'  {f} := {f}_bound\n' for f in fields)+'\ntheorem trained_view : toModel trainedRust = TransformerInt.Gen.weights := by\n  simp only [toModel, trainedRust, '+', '.join(f'{f}_view' for f in fields)+', TransformerInt.Gen.weights]\n')
    return files

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('checkpoint',nargs='?',type=Path,default=ROOT.parent/'lean-checked-network/transformer/runs/best.npz')
    p.add_argument('--gate-weights',type=Path,default=ROOT/'pilot/transformer-int/TransformerInt/Gen')
    p.add_argument('--check',action='store_true'); a=p.parse_args()
    digest=gen.sha256_file(a.checkpoint)
    if digest!=gen.CHECKPOINT_SHA256: raise SystemExit('checkpoint hash mismatch')
    t=gen.load_quantised(a.checkpoint)
    # Verify the gate 4 literal sources against the same quantisation before emitting references.
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        gate.write_weights(Path(d),t,digest)
        for src in Path(d).rglob('*.lean'):
            actual=a.gate_weights/src.relative_to(d)
            if not actual.exists():
                if a.check: raise SystemExit(f'missing gate 4 weights: {actual}')
                actual.parent.mkdir(parents=True,exist_ok=True)
                actual.write_bytes(src.read_bytes())
            if actual.read_bytes()!=src.read_bytes(): raise SystemExit(f'gate 4 weights mismatch: {actual}')
    files=render(t)
    for path,text in files.items():
        dest=ROOT/path
        if a.check:
            if not dest.exists() or dest.read_text()!=text: raise SystemExit(f'generated mismatch: {path}')
        elif not dest.exists() or dest.read_text()!=text:
            dest.parent.mkdir(parents=True,exist_ok=True); dest.write_text(text)
    print(json.dumps({'checkpoint_sha256':digest,'files':{p:hashlib.sha256(s.encode()).hexdigest() for p,s in files.items()},'mode':'check' if a.check else 'write'},indent=2))
if __name__=='__main__': main()
