# tables: what depends on (head, position, token) only


def build_tables(model):
    tb = {}
    for j in (0, 1):
        tb[f"s{j}"] = [[model.score(h, tok, j) for tok in range(P)] for h in range(N_HEADS)]
        tb[f"v{j}"] = [[model.val(h, tok, j) for tok in range(P)] for h in range(N_HEADS)]
    tb["s2"] = [model.score(h, EQ, 2) for h in range(N_HEADS)]
    tb["v2"] = [model.val(h, EQ, 2) for h in range(N_HEADS)]
    return tb


def write_tables(gen_dir, tb):
    parts = []
    for j in (0, 1):
        parts.append(matrix(f"s{j}", tb[f"s{j}"], f"Attention scores at position {j}: head, token."))
        for h in range(N_HEADS):
            parts.append(matrix(f"v{j}_{h}", tb[f"v{j}"][h], f"Value vectors of head {h} at position {j}: token, head index."))
        parts.append(f"def v{j} : List (List (List Int)) := {names(f'v{j}', N_HEADS)}")
    parts.append(f"/-- Attention scores of `=` at position 2: head. -/\ndef s2 : List Int := {vec(tb['s2'])}")
    parts.append(matrix("v2", tb["v2"], "Value vectors of `=` at position 2: head, head index."))
    emit(gen_dir / "W" / "TablesData.lean", module([], "\n\n".join(parts)))
    body = """/-- The scores and the value vectors of every (head, position, token).
`TablesOk.lean` proves each entry equal to its definition from `weights`. -/
def tables : Tables := { s0 := s0, s1 := s1, s2 := s2, v0 := v0, v1 := v1, v2 := v2 }"""
    emit(gen_dir / "Tables.lean", module(["TransformerInt.Fast", "TransformerInt.Gen.W.TablesData"], body, opts=""))


HEAD_MATS = (("wq", "WQ", 32), ("wk", "WK", 32), ("wv", "WV", 32), ("wo", "WO", 128))


def write_packed(gen_dir, t):
    """The entry bounds and the packed rows: data only, proved in Static.lean."""
    base = packing_base()
    b = {k: absmax(t[k]) for k in ("WQ", "WK", "WV", "WO", "Win", "Wout", "U")}
    parts = []
    for h in range(N_HEADS):
        parts.append(f"def pwo_{h} : List Int := {hexvec([pk(r, base) for r in t['WO'][h]])}")
    parts.append(f"def pwin : List Int := {hexvec([pk(r, base) for r in t['Win']])}")
    parts.append(f"def pwout : List Int := {hexvec([pk(r, base) for r in t['Wout']])}")
    parts.append(f"def pu : List Int := {hexvec([pk(r, base) for r in t['U']])}")
    emit(gen_dir / "W" / "PackedData.lean", module([], "\n\n".join(parts)))
    body = f"""/-- The largest absolute entry of each matrix that is multiplied in packed form. -/
def bounds : Bounds := {{
  wq := {b['WQ']}, wk := {b['WK']}, wv := {b['WV']}, wo := {b['WO']}, win := {b['Win']}, wout := {b['Wout']}, u := {b['U']} }}

/-- `pkRows` of `wo` (per head), `win`, `wout`, `u`, at the base {base} of `Fast.lean`.
`Static.lean` proves each list equal to `pkRows` of the weights. -/
def packed : Packed := {{ wo := {names('pwo', N_HEADS)}, win := pwin, wout := pwout, u := pu }}"""
    emit(gen_dir / "Packed.lean", module(["TransformerInt.Fast", "TransformerInt.Gen.W.PackedData"], body, opts=""))
    return b


def by_head(name):
    arms = "\n".join(f"    | {h}, _ => exact {name}_{h}" for h in range(N_HEADS))
    return f"""    intro h hh
    match h, hh with
{arms}
    | n + 4, hh => exact absurd hh (by omega)"""


def write_static(gen_dir, b):
    parts = []
    for low, name, width in HEAD_MATS:
        for h in range(N_HEADS):
            parts.append(f"theorem {low}_ok_{h} : rowsOk {width} {b[name]} (nth [] weights.{low} {h}) = true := by decide +kernel")
    parts.append(f"theorem win_ok : rowsOk 512 {b['Win']} weights.win = true := by decide +kernel")
    parts.append(f"theorem wout_ok : rowsOk 128 {b['Wout']} weights.wout = true := by decide +kernel")
    parts.append(f"theorem u_ok : rowsOk 113 {b['U']} weights.u = true := by decide +kernel")
    for h in range(N_HEADS):
        parts.append(f"theorem pwo_ok_{h} : nth [] packed.wo {h} = pkRows (nth [] weights.wo {h}) := by decide +kernel")
    parts.append("theorem pwin_ok : packed.win = pkRows weights.win := by decide +kernel")
    parts.append("theorem pwout_ok : packed.wout = pkRows weights.wout := by decide +kernel")
    parts.append("theorem pu_ok : packed.u = pkRows weights.u := by decide +kernel")
    parts.append(f"""/-- Shapes and entry bounds of the matrices, and the packed rows of `Packed.lean`. -/
theorem static_ok : StaticOk weights bounds packed where
  wq := by
{by_head('wq_ok')}
  wk := by
{by_head('wk_ok')}
  wv := by
{by_head('wv_ok')}
  wo := by
{by_head('wo_ok')}
  win := win_ok
  wout := wout_ok
  u := u_ok
  pwo := by
{by_head('pwo_ok')}
  pwin := pwin_ok
  pwout := pwout_ok
  pu := pu_ok""")
    emit(gen_dir / "Static.lean", module(
        ["TransformerInt.Fast", "TransformerInt.Gen.Weights", "TransformerInt.Gen.Packed"],
        "\n\n".join(parts), opts="set_option Elab.async false\n"))


def write_tables_ok(gen_dir):
    """Per head: the kernel runs the packed projections on every token; `fastScore_eq` and
    `fastValue_eq` turn that into statements about the model's own `keyScore` and `value`."""
    for h in range(N_HEADS):
        parts = []
        for j in (0, 1):
            parts.append(f"""theorem s{j}_fast_{h} : ∀ t, t < 113 →
    fastScore weights bounds {h} (embed weights EQ 2) (embed weights t {j}) = some (nth 0 (nth [] tables.s{j} {h}) t) := by
  decide +kernel

theorem s{j}_ok_{h} : ∀ t, t < 113 →
    keyScore weights {h} (embed weights EQ 2) (embed weights t {j}) = nth 0 (nth [] tables.s{j} {h}) t :=
  fun t ht => fastScore_eq static_ok {h} (by decide) _ _ _ (s{j}_fast_{h} t ht)

theorem v{j}_fast_{h} : ∀ t, t < 113 →
    fastValue weights bounds {h} (embed weights t {j}) = some (nth [] (nth [] tables.v{j} {h}) t) := by
  decide +kernel

theorem v{j}_ok_{h} : ∀ t, t < 113 →
    value weights {h} (embed weights t {j}) = nth [] (nth [] tables.v{j} {h}) t :=
  fun t ht => fastValue_eq static_ok {h} (by decide) _ _ (v{j}_fast_{h} t ht)""")
        parts.append(f"""theorem s2_fast_{h} :
    fastScore weights bounds {h} (embed weights EQ 2) (embed weights EQ 2) = some (nth 0 tables.s2 {h}) := by
  decide +kernel

theorem s2_ok_{h} : keyScore weights {h} (embed weights EQ 2) (embed weights EQ 2) = nth 0 tables.s2 {h} :=
  fastScore_eq static_ok {h} (by decide) _ _ _ s2_fast_{h}

theorem v2_fast_{h} : fastValue weights bounds {h} (embed weights EQ 2) = some (nth [] tables.v2 {h}) := by
  decide +kernel

theorem v2_ok_{h} : value weights {h} (embed weights EQ 2) = nth [] tables.v2 {h} :=
  fastValue_eq static_ok {h} (by decide) _ _ v2_fast_{h}""")
        emit(gen_dir / f"TabOk{h}.lean", module(
            ["TransformerInt.Fast", "TransformerInt.Gen.Weights", "TransformerInt.Gen.Tables",
             "TransformerInt.Gen.Static"], "\n\n".join(parts), opts="set_option Elab.async false\n"))

    body = """/-- Every table entry equals its definition from `weights`. -/
theorem tables_ok : TablesOk weights tables where
""" + "\n".join(f"  {n} := by\n{by_head(n + '_ok')}" for n in ("s0", "s1", "s2", "v0", "v1", "v2"))
    emit(gen_dir / "TablesOk.lean", module(
        ["TransformerInt.Fast"] + [f"TransformerInt.Gen.TabOk{h}" for h in range(N_HEADS)], body, opts=""))


