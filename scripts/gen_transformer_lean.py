#!/usr/bin/env python3
"""Generate the Lean project that kernel-checks the integer transformer (gate 4 pilot).

Standard library only. The integers come from gen_transformer_weights.py (same checkpoint, same
quantisation, same exponential tables), so the Lean model reads what rust/transformer/src/weights.rs
holds. The score and value tables come from check_transformer_int.py, the exact Python reference.

The output directory becomes a standalone Lake project (core Lean, no Mathlib):

  hand-written, copied from pilot/transformer-int/ unless OUT is that directory:
    lakefile.toml, lean-toolchain, TransformerInt.lean
    TransformerInt/Model.lean     the model of rust/transformer/src/lib.rs, on Int
    TransformerInt/Fast.lean      the packed evaluator and the proof that it equals the model
  generated, everything under TransformerInt/Gen/:
    W/*.lean, Weights.lean        the weights and the four exponential tables
    Tables.lean                   attention scores and value vectors per (head, position, token)
    Static.lean                   shapes and entry bounds of WO, WIN, WOUT, U (kernel-checked)
    TabOk{0..3}.lean, TablesOk.lean   every table entry equals its definition (kernel-checked)
    Row{a}.lean                   theorem row_{a} : for every b < 113, predict a b = (a + b) % 113
    AllRows.lean                  adds_mod_113, only with all 113 rows
    Eval.lean                     #eval of the model against the Python reference logits (a test)
    Pair_{a}_{b}.lean, Direct_{a}_{b}.lean   single pairs, for timing (--pairs, --direct)

Usage:
  gen_transformer_lean.py CHECKPOINT.npz OUT [--rows 0,21 | --rows all] [--pairs 0:0,21:56]
                          [--direct 0:0] [--eval-rows 0,21] [--chunks N] [--hand-only]
  --rows       the rows to write a module for (default: 0,21)
  --chunks     split a row's kernel check into N declarations (default 1)
  --hand-only  copy the hand-written files and stop
  --allow-other-checkpoint   skip the sha256 pin (for experiments only)
"""

import argparse
import hashlib
import shutil
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no scripts/__pycache__ in the repository
sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_transformer_int as ref  # noqa: E402
import gen_transformer_weights as gen  # noqa: E402

ROOT = gen.ROOT
HAND = ROOT / "pilot" / "transformer-int"
HAND_FILES = [
    "lakefile.toml",
    "lean-toolchain",
    "TransformerInt.lean",
    "TransformerInt/Model.lean",
    "TransformerInt/Fast.lean",
]

P, EQ = ref.P, ref.EQ
N_HEADS, D_MODEL, D_HEAD, D_MLP = ref.N_HEADS, ref.D_MODEL, ref.D_HEAD, ref.D_MLP

HEADER = "-- @generated by scripts/gen_transformer_lean.py. Do not edit.\n"
OPTS = "set_option maxRecDepth 100000\nset_option maxHeartbeats 4000000\n"


def lit(x):
    """An Int literal written as a constructor, so the kernel does no typeclass unfolding."""
    return f"(.ofNat {x})" if x >= 0 else f"(.negSucc {-x - 1})"


def vec(v):
    return "[" + ", ".join(lit(x) for x in v) + "]"


def names(prefix, n):
    return "[" + ", ".join(f"{prefix}_{i}" for i in range(n)) + "]"


def matrix(prefix, rows, doc):
    """One def per row (a def of 65,536 literals is too deep for the elaborator), then the list."""
    out = [f"def {prefix}_{i} : List Int := {vec(r)}" for i, r in enumerate(rows)]
    out.append("")
    out.append(f"/-- {doc} -/")
    out.append(f"def {prefix} : List (List Int) := {names(prefix, len(rows))}")
    return "\n".join(out)


def module(imports, body, opts=OPTS, ns="TransformerInt.Gen"):
    """A generated module. Without imports it holds data only and opens nothing."""
    imp = "".join(f"import {m}\n" for m in imports) + ("\n" if imports else "")
    opn = "open TransformerInt\n\n" if imports else ""
    return f"{HEADER}{imp}{opts}\nnamespace {ns}\n\n{opn}{body}\n\nend {ns}\n"


def absmax(nested):
    while isinstance(nested[0], list):
        nested = [v for row in nested for v in row]
    return max(max(nested), -min(nested))


# ----------------------------------------------------------------------------------------------
# weights


def write_weights(gen_dir, t, checkpoint_sha):
    w = gen_dir / "W"
    w.mkdir(parents=True, exist_ok=True)
    base = []  # the data modules import nothing, so a change to the model does not rebuild them
    emb = "\n\n".join([
        matrix("tok", t["tok"], "Token embedding, scale 2^8: 114 rows of 128."),
        matrix("pos", t["pos"], "Position embedding, scale 2^8: 3 rows of 128."),
        f"/-- MLP input bias, scale 2^32. -/\ndef bin : List Int := {vec(t['bin'])}",
        f"/-- MLP output bias, scale 2^40. -/\ndef bout : List Int := {vec(t['bout'])}",
        f"/-- `expN[n]` = round(2^30 * exp(-n)). -/\ndef expN : List Int := {vec(t['EXP_N'])}",
        f"/-- `exp2[b]` = round(2^30 * exp(-b / 2^8)). -/\ndef exp2 : List Int := {vec(t['EXP_2'])}",
        f"/-- `exp1[b]` = round(2^30 * exp(-b / 2^16)). -/\ndef exp1 : List Int := {vec(t['EXP_1'])}",
        f"/-- `exp0[b]` = round(2^30 * exp(-b / 2^24)). -/\ndef exp0 : List Int := {vec(t['EXP_0'])}",
    ])
    (w / "Emb.lean").write_text(module(base, emb))
    mods = ["Emb"]
    docs = {
        "WQ": "Query matrices, scale 2^8, with 1/sqrt(32) folded in: head, stream index, head index.",
        "WK": "Key matrices, scale 2^8: head, stream index, head index.",
        "WV": "Value matrices, scale 2^8: head, stream index, head index.",
        "WO": "Output matrices, scale 2^8: head, head index, stream index.",
    }
    for name in ("WQ", "WK", "WV", "WO"):
        low = name.lower()
        parts = [matrix(f"{low}_{h}", t[name][h], f"Head {h} of `{low}`.") for h in range(N_HEADS)]
        parts.append(f"/-- {docs[name]} -/\ndef {low} : List (List (List Int)) := {names(low, N_HEADS)}")
        (w / f"{name}.lean").write_text(module(base, "\n\n".join(parts)))
        mods.append(name)
    (w / "Win.lean").write_text(module(base, matrix("win", t["Win"], "MLP input matrix, scale 2^8: stream index, hidden index.")))
    (w / "Wout.lean").write_text(module(base, matrix("wout", t["Wout"], "MLP output matrix, scale 2^8: hidden index, stream index.")))
    (w / "U.lean").write_text(module(base, matrix("u", t["U"], "Unembedding, scale 2^8: stream index, answer.")))
    mods += ["Win", "Wout", "U"]
    body = f"""/-- The weights of `rust/transformer/src/weights.rs`.
Checkpoint: lean-checked-network transformer/runs/best.npz, sha256 {checkpoint_sha}.
Quantisation: gen_transformer_weights.py quantise, S = {gen.S}. `.ofNat n` is the integer n and
`.negSucc n` is the integer -(n + 1). -/
def weights : Weights := {{
  tok := tok, pos := pos, wq := wq, wk := wk, wv := wv, wo := wo,
  win := win, bin := bin, wout := wout, bout := bout, u := u,
  expN := expN, exp2 := exp2, exp1 := exp1, exp0 := exp0 }}"""
    (gen_dir / "Weights.lean").write_text(
        module(["TransformerInt.Model"] + [f"TransformerInt.Gen.W.{m}" for m in mods], body, opts=""))


# ----------------------------------------------------------------------------------------------
# tables: what depends on (head, position, token) only


def build_tables(model):
    tb = {}
    for j in (0, 1):
        tb[f"s{j}"] = [[model.score(h, tok, j) for tok in range(P)] for h in range(N_HEADS)]
        tb[f"v{j}"] = [[model.val(h, tok, j) for tok in range(P)] for h in range(N_HEADS)]
    tb["s2"] = [model.score(h, EQ, 2) for h in range(N_HEADS)]
    tb["v2"] = [model.val(h, EQ, 2) for h in range(N_HEADS)]
    return tb


def write_tables(gen_dir, tb):
    parts = []
    for j in (0, 1):
        parts.append(matrix(f"s{j}", tb[f"s{j}"], f"Attention scores at position {j}: head, token."))
        for h in range(N_HEADS):
            parts.append(matrix(f"v{j}_{h}", tb[f"v{j}"][h], f"Value vectors of head {h} at position {j}: token, head index."))
        parts.append(f"def v{j} : List (List (List Int)) := {names(f'v{j}', N_HEADS)}")
    parts.append(f"/-- Attention scores of `=` at position 2: head. -/\ndef s2 : List Int := {vec(tb['s2'])}")
    parts.append(matrix("v2", tb["v2"], "Value vectors of `=` at position 2: head, head index."))
    parts.append("""/-- The scores and the value vectors of every (head, position, token).
`TablesOk.lean` proves each entry equal to its definition from `weights`. -/
def tables : Tables := { s0 := s0, s1 := s1, s2 := s2, v0 := v0, v1 := v1, v2 := v2 }""")
    (gen_dir / "Tables.lean").write_text(module(["TransformerInt.Fast"], "\n\n".join(parts)))


def write_static(gen_dir, t):
    b = {k: absmax(t[k]) for k in ("WO", "Win", "Wout", "U")}
    heads = "\n\n".join(
        f"theorem wo_{h}_ok : rowsOk 128 {b['WO']} (nth [] weights.wo {h}) = true := by decide +kernel"
        for h in range(N_HEADS))
    body = f"""/-- The largest absolute entry of `wo`, `win`, `wout`, `u`. -/
def bounds : Bounds := {{ wo := {b['WO']}, win := {b['Win']}, wout := {b['Wout']}, u := {b['U']} }}

{heads}

theorem win_ok : rowsOk 512 {b['Win']} weights.win = true := by decide +kernel

theorem wout_ok : rowsOk 128 {b['Wout']} weights.wout = true := by decide +kernel

theorem u_ok : rowsOk 113 {b['U']} weights.u = true := by decide +kernel

/-- Shapes and entry bounds of the four matrices the packed evaluator multiplies by. -/
theorem static_ok : StaticOk weights bounds where
  wo := by
    intro h hh
    match h, hh with
    | 0, _ => exact wo_0_ok
    | 1, _ => exact wo_1_ok
    | 2, _ => exact wo_2_ok
    | 3, _ => exact wo_3_ok
    | n + 4, hh => exact absurd hh (by omega)
  win := win_ok
  wout := wout_ok
  u := u_ok"""
    (gen_dir / "Static.lean").write_text(
        module(["TransformerInt.Fast", "TransformerInt.Gen.Weights"], body, opts="set_option Elab.async false\n"))


def write_tables_ok(gen_dir):
    for h in range(N_HEADS):
        body = f"""theorem s0_{h} : ∀ t, t < 113 →
    keyScore weights {h} (embed weights 113 2) (embed weights t 0) = nth 0 (nth [] tables.s0 {h}) t := by
  decide +kernel

theorem s1_{h} : ∀ t, t < 113 →
    keyScore weights {h} (embed weights 113 2) (embed weights t 1) = nth 0 (nth [] tables.s1 {h}) t := by
  decide +kernel

theorem s2_{h} :
    keyScore weights {h} (embed weights 113 2) (embed weights 113 2) = nth 0 tables.s2 {h} := by
  decide +kernel

theorem v0_{h} : ∀ t, t < 113 →
    value weights {h} (embed weights t 0) = nth [] (nth [] tables.v0 {h}) t := by
  decide +kernel

theorem v1_{h} : ∀ t, t < 113 →
    value weights {h} (embed weights t 1) = nth [] (nth [] tables.v1 {h}) t := by
  decide +kernel

theorem v2_{h} : value weights {h} (embed weights 113 2) = nth [] tables.v2 {h} := by
  decide +kernel"""
        (gen_dir / f"TabOk{h}.lean").write_text(module(
            ["TransformerInt.Fast", "TransformerInt.Gen.Weights", "TransformerInt.Gen.Tables"], body,
            opts="set_option Elab.async false\n"))

    def field(name, with_tok):
        arms = "\n".join(f"    | {h}, _ => exact {name}_{h}" for h in range(N_HEADS))
        return f"""  {name} := by
    intro h hh
    match h, hh with
{arms}
    | n + 4, hh => exact absurd hh (by omega)"""

    body = """/-- Every table entry equals its definition from `weights`. -/
theorem tables_ok : TablesOk weights tables where
""" + "\n".join(field(n, n[1] != "2") for n in ("s0", "s1", "s2", "v0", "v1", "v2"))
    (gen_dir / "TablesOk.lean").write_text(module(
        ["TransformerInt.Fast"] + [f"TransformerInt.Gen.TabOk{h}" for h in range(N_HEADS)], body, opts=""))


# ----------------------------------------------------------------------------------------------
# rows


ROW_IMPORTS = ["TransformerInt.Fast", "TransformerInt.Gen.Weights", "TransformerInt.Gen.Tables",
               "TransformerInt.Gen.Static", "TransformerInt.Gen.TablesOk"]


def write_row(gen_dir, a, chunks):
    """Row `a`: the kernel runs the packed evaluator on every b, in `chunks` declarations."""
    edges = [round(i * P / chunks) for i in range(chunks + 1)]
    parts = []
    for i in range(chunks):
        lo, hi = edges[i], edges[i + 1]
        parts.append(f"""theorem fast_{a}_{i} : ∀ b, b < {hi - lo} →
    fastPredict weights tables bounds {a} ({lo} + b) = some (({a} + ({lo} + b)) % 113) := by
  decide +kernel""")
    arms = []
    for i in range(chunks):
        lo, hi = edges[i], edges[i + 1]
        arms.append(f"""  · have h := fast_{a}_{i} (b - {lo}) (by omega)
    rw [show {lo} + (b - {lo}) = b by omega] at h
    exact h""")
    if chunks == 1:
        split = "  have hc : b < 113 := hb\n" + arms[0]
    else:
        conds = " ∨ ".join(f"({edges[i]} ≤ b ∧ b < {edges[i + 1]})" for i in range(chunks))
        split = f"  have hc : {conds} := by omega\n  rcases hc with " + " | ".join(["hc"] * chunks) + "\n" + "\n".join(arms)
    parts.append(f"""/-- The packed evaluator answers ({a} + b) % 113 for every b. -/
theorem fast_{a} : ∀ b, b < 113 → fastPredict weights tables bounds {a} b = some (({a} + b) % 113) := by
  intro b hb
{split}

/-- Row {a} of the addition table: the model answers ({a} + b) % 113 for every b. -/
theorem row_{a} : ∀ b, b < 113 → predict weights {a} b = some (({a} + b) % 113) := by
  intro b hb
  exact fastPredict_sound static_ok tables_ok {a} b (by decide) hb _ (fast_{a} b hb)""")
    (gen_dir / f"Row{a}.lean").write_text(module(ROW_IMPORTS, "\n\n".join(parts), opts="set_option Elab.async false\n"))


def write_all_rows(gen_dir):
    arms = "\n".join(f"  | {a}, _ => exact row_{a}" for a in range(P))
    body = f"""/-- The integer transformer adds mod 113 on every input pair. -/
theorem adds_mod_113 : ∀ a, a < 113 → ∀ b, b < 113 → predict weights a b = some ((a + b) % 113) := by
  intro a ha
  match a, ha with
{arms}
  | n + 113, h => exact absurd h (by omega)"""
    (gen_dir / "AllRows.lean").write_text(
        module([f"TransformerInt.Gen.Row{a}" for a in range(P)], body, opts=""))


def write_pair(gen_dir, a, b):
    body = f"""theorem fast_pair_{a}_{b} :
    fastPredict weights tables bounds {a} {b} = some {(a + b) % P} := by
  decide +kernel

theorem pair_{a}_{b} : predict weights {a} {b} = some {(a + b) % P} :=
  fastPredict_sound static_ok tables_ok {a} {b} (by decide) (by decide) _ fast_pair_{a}_{b}"""
    (gen_dir / f"Pair_{a}_{b}.lean").write_text(module(ROW_IMPORTS, body, opts="set_option Elab.async false\n"))


def write_direct(gen_dir, a, b):
    """The model itself in the kernel, no tables and no packing: the baseline."""
    body = f"""theorem direct_{a}_{b} : predict weights {a} {b} = some {(a + b) % P} := by
  decide +kernel"""
    (gen_dir / f"Direct_{a}_{b}.lean").write_text(module(
        ["TransformerInt.Model", "TransformerInt.Gen.Weights"], body, opts="set_option Elab.async false\n"))


def write_eval(gen_dir, model, pairs):
    """`#eval` of the Lean model against the Python reference: a test, not a proof."""
    rows = []
    for a, b in pairs:
        out, _ = model.forward(a, b)
        rows.append(f"  ({a}, {b}, {vec(out)})")
    body = f"""/-- Logits of the Python reference `scripts/check_transformer_int.py`: `(a, b, logits)`. -/
def expected : List (Nat × Nat × List Int) := [
{(",\n").join(rows)}]

/-- Pairs on which the Lean model's logits differ from the reference. -/
def mismatches : List (Nat × Nat) :=
  (expected.filter fun (a, b, l) => logits weights a b != some l).map fun (a, b, _) => (a, b)

/-- Pairs on which the Lean model's answer is not `(a + b) % 113`. -/
def wrong : List (Nat × Nat) :=
  (expected.filter fun (a, b, _) => predict weights a b != some ((a + b) % 113)).map fun (a, b, _) => (a, b)

#eval s!"pairs compared: {{expected.length}}; logits compared: {{(expected.map fun (_, _, l) => l.length).sum}}"
#eval s!"pairs with a different logit: {{mismatches.length}} {{mismatches}}"
#eval s!"pairs with a wrong answer: {{wrong.length}} {{wrong}}"
#guard mismatches.isEmpty && wrong.isEmpty"""
    (gen_dir / "Eval.lean").write_text(module(["TransformerInt.Model", "TransformerInt.Gen.Weights"], body))


# ----------------------------------------------------------------------------------------------


def parse_pairs(text):
    return [tuple(int(x) for x in item.split(":")) for item in text.split(",") if item]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("checkpoint", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--rows", default="0,21")
    ap.add_argument("--chunks", type=int, default=1)
    ap.add_argument("--pairs", default="")
    ap.add_argument("--direct", default="")
    ap.add_argument("--eval-rows", default="0,21")
    ap.add_argument("--hand-only", action="store_true")
    ap.add_argument("--allow-other-checkpoint", action="store_true")
    args = ap.parse_args()

    out = args.out.resolve()
    if out != HAND.resolve():
        for rel in HAND_FILES:
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(HAND / rel, out / rel)
        print(f"copied {len(HAND_FILES)} hand-written files from {HAND.relative_to(ROOT)}")
    if args.hand_only:
        return 0

    checkpoint_sha = gen.sha256_file(args.checkpoint)
    if checkpoint_sha != gen.CHECKPOINT_SHA256 and not args.allow_other_checkpoint:
        print(f"FAIL: checkpoint sha256 {checkpoint_sha}, pinned {gen.CHECKPOINT_SHA256}", file=sys.stderr)
        return 1
    t = gen.load_quantised(args.checkpoint)
    model = ref.Model(t, ref.Stats(partials=False))
    gen_dir = out / "TransformerInt" / "Gen"
    gen_dir.mkdir(parents=True, exist_ok=True)

    write_weights(gen_dir, t, checkpoint_sha)
    write_tables(gen_dir, build_tables(model))
    write_static(gen_dir, t)
    write_tables_ok(gen_dir)
    rows = list(range(P)) if args.rows == "all" else [int(x) for x in args.rows.split(",") if x]
    for a in rows:
        write_row(gen_dir, a, args.chunks)
    if len(rows) == P:
        write_all_rows(gen_dir)
    for a, b in parse_pairs(args.pairs):
        write_pair(gen_dir, a, b)
    for a, b in parse_pairs(args.direct):
        write_direct(gen_dir, a, b)
    eval_rows = [int(x) for x in args.eval_rows.split(",") if x]
    sample = [(a, b) for a in eval_rows for b in range(P)]
    sample += [(a, b) for a in (0, 1, 56, 96, 112) for b in (0, 1, 21, 73, 112) if (a, b) not in sample]
    write_eval(gen_dir, model, sample)

    files = sorted(p for p in gen_dir.rglob("*.lean"))
    digest = hashlib.sha256()
    for p in files:
        digest.update(p.relative_to(out).as_posix().encode() + b"\0" + p.read_bytes())
    print(f"checkpoint sha256 {checkpoint_sha}")
    print(f"wrote {len(files)} generated files under {gen_dir}, {sum(p.stat().st_size for p in files)} bytes, sha256 over them {digest.hexdigest()}")
    print(f"rows: {rows}; chunks per row: {args.chunks}; eval sample: {len(sample)} pairs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
