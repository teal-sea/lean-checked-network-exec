def parse_pairs(text):
    return [tuple(int(x) for x in item.split(":")) for item in text.split(",") if item]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("checkpoint", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--rows", default="0,21")
    ap.add_argument("--chunks", type=int, default=1)
    ap.add_argument("--pairs", default="")
    ap.add_argument("--direct", default="")
    ap.add_argument("--prefix", default="")
    ap.add_argument("--eval-rows", default="0,21")
    ap.add_argument("--hand-only", action="store_true")
    ap.add_argument("--allow-other-checkpoint", action="store_true")
    args = ap.parse_args()

    out = args.out.resolve()
    if out != HAND.resolve():
        for rel in HAND_FILES:
            (out / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(HAND / rel, out / rel)
        print(f"copied {len(HAND_FILES)} hand-written files from {HAND.relative_to(ROOT)}")
    if args.hand_only:
        return 0

    checkpoint_sha = gen.sha256_file(args.checkpoint)
    if checkpoint_sha != gen.CHECKPOINT_SHA256 and not args.allow_other_checkpoint:
        print(f"FAIL: checkpoint sha256 {checkpoint_sha}, pinned {gen.CHECKPOINT_SHA256}", file=sys.stderr)
        return 1
    t = gen.load_quantised(args.checkpoint)
    model = ref.Model(t, ref.Stats(partials=False))
    gen_dir = out / "TransformerInt" / "Gen"
    gen_dir.mkdir(parents=True, exist_ok=True)

    write_weights(gen_dir, t, checkpoint_sha)
    write_tables(gen_dir, build_tables(model))
    write_static(gen_dir, write_packed(gen_dir, t))
    write_tables_ok(gen_dir)
    rows = list(range(P)) if args.rows == "all" else [int(x) for x in args.rows.split(",") if x]
    for a in rows:
        write_row(gen_dir, a, args.chunks)
    if len(rows) == P:
        write_all_rows(gen_dir)
    for a, b in parse_pairs(args.pairs):
        write_pair(gen_dir, a, b)
    for a, b in parse_pairs(args.direct):
        write_direct(gen_dir, a, b)
    for a, n in parse_pairs(args.prefix):
        write_prefix(gen_dir, a, n)
    write_base(gen_dir)
    eval_rows = [int(x) for x in args.eval_rows.split(",") if x]
    sample = [(a, b) for a in eval_rows for b in range(P)]
    sample += [(a, b) for a in (0, 1, 56, 96, 112) for b in (0, 1, 21, 73, 112) if (a, b) not in sample]
    write_eval(gen_dir, model, sample)

    files = sorted(p for p in gen_dir.rglob("*.lean"))
    digest = hashlib.sha256()
    for p in files:
        digest.update(p.relative_to(out).as_posix().encode() + b"\0" + p.read_bytes())
    print(f"checkpoint sha256 {checkpoint_sha}")
    print(f"wrote {len(files)} generated files under {gen_dir}, {sum(p.stat().st_size for p in files)} bytes, sha256 over them {digest.hexdigest()}")
    print(f"rows: {rows}; chunks per row: {args.chunks}; eval sample: {len(sample)} pairs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
